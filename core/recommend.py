"""The recommendation engine.

Every suggestion must answer three questions, in this order:

    1. What should the user do now?
    2. Why that, and not something else?
    3. What improvement will this likely create?

Candidates are generated by rules over measured analytics, given an urgency
between 0 and 100, then multiplied by whatever the feedback loop has learnt
about which kinds of advice this particular user acts on. Nothing here is
generative: the sentences are templates filled with real numbers, which is
exactly why they can be trusted.

The engine is deliberately conservative about claiming impact. Where a gain can
be computed from the readiness weights it is stated numerically; where it cannot,
it says what will change qualitatively instead of inventing a number.
"""

from datetime import date, timedelta

from . import content, feedback, readiness

# Rough index points per unit, derived from readiness.WEIGHTS. Used only to
# order suggestions and to phrase "worth about X" - never presented as precise.
COVERAGE_W = readiness.WEIGHTS["coverage"]
ACCURACY_W = readiness.WEIGHTS["accuracy"]
VOLUME_W = readiness.WEIGHTS["volume"]
CONSISTENCY_W = readiness.WEIGHTS["consistency"]


def _hash(route, **kw):
    return dict(route=route, **kw)


